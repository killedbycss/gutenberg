"""Эталонные наборы символов для проверки полноты покрытия шрифта.

Проверка отвечает на вопрос: «есть ли в шрифте глиф для каждого символа из
ожидаемого набора?». Ожидаемый набор разбит на понятные категории
(латиница, кириллица, диакритика, пунктуация) — так отчёт о недостающих
глифах сразу говорит, *чего именно* не хватает.

Пресеты:
    basic     — русская кириллица + базовая латиница (ASCII) + распространённая
                диакритика и пунктуация. Значение по умолчанию, покрывает
                большинство задач.
    extended  — дополнительно украинский/белорусский/сербский, Latin Extended-A,
                типографские знаки и дроби.

Каждая категория — это (ключ, человекочитаемая метка, множество кодпойнтов).
Категории намеренно не пересекаются, чтобы счётчики в отчёте суммировались.
"""

from __future__ import annotations


def _r(start: int, end: int) -> set[int]:
    """Замкнутый диапазон кодпойнтов [start, end]."""
    return set(range(start, end + 1))


# --- Латиница (базовая, видимый ASCII) ------------------------------------
# 0x20–0x7E: буквы, цифры и вся ASCII-пунктуация. Пробел (0x20) включён —
# без него шрифт в принципе нерабочий.
LATIN_BASIC = _r(0x20, 0x7E)

# --- Русская кириллица -----------------------------------------------------
CYRILLIC_RU = _r(0x0410, 0x044F) | {0x0401, 0x0451}  # А–я + Ё, ё

# Кириллица для украинского/белорусского/сербского и др.
CYRILLIC_EXT = {
    0x0402, 0x0403, 0x0404, 0x0405, 0x0406, 0x0407, 0x0408, 0x0409,
    0x040A, 0x040B, 0x040C, 0x040E, 0x040F,
    0x0452, 0x0453, 0x0454, 0x0455, 0x0456, 0x0457, 0x0458, 0x0459,
    0x045A, 0x045B, 0x045C, 0x045E, 0x045F,
    0x0490, 0x0491,  # Ґ ґ (украинская)
}

# --- Диакритика (акцентированная латиница) ---------------------------------
# Latin-1 Supplement (буквы) без знаков умножения/деления (× ÷).
DIACRITICS_BASIC = (_r(0x00C0, 0x00FF) - {0x00D7, 0x00F7}) | {
    0x0152, 0x0153,  # Œ œ
    0x0178,          # Ÿ
    0x0160, 0x0161,  # Š š
    0x017D, 0x017E,  # Ž ž
}

# Latin Extended-A целиком (польский, чешский, венгерский, турецкий и т.д.).
DIACRITICS_EXT = _r(0x0100, 0x017F)

# --- Пунктуация и типографские знаки ---------------------------------------
PUNCTUATION_BASIC = {
    0x00A0,  # неразрывный пробел
    0x00A1,  # ¡
    0x00A2, 0x00A3, 0x00A5,  # ¢ £ ¥
    0x00A7,  # §
    0x00A9,  # ©
    0x00AB, 0x00BB,  # « »
    0x00AE,  # ®
    0x00B0,  # °
    0x00B1,  # ±
    0x00B7,  # ·
    0x00BF,  # ¿
    0x00D7, 0x00F7,  # × ÷
    0x2013, 0x2014,  # – —
    0x2018, 0x2019, 0x201A,  # ' ' ‚
    0x201C, 0x201D, 0x201E,  # " " „
    0x2020, 0x2021,  # † ‡
    0x2022,  # •
    0x2026,  # …
    0x2030,  # ‰
    0x2039, 0x203A,  # ‹ ›
    0x20AC,  # €
    0x20BD,  # ₽
    0x2116,  # №
    0x2122,  # ™
    0x2212,  # − (минус)
}

PUNCTUATION_EXT = {
    0x2044,  # ⁄ дробная черта
    0x00BC, 0x00BD, 0x00BE,  # ¼ ½ ¾
    0x2153, 0x2154,  # ⅓ ⅔
    0x215B, 0x215C, 0x215D, 0x215E,  # ⅛ ⅜ ⅝ ⅞
    0x2190, 0x2191, 0x2192, 0x2193,  # ← ↑ → ↓
    0x2260, 0x2264, 0x2265,  # ≠ ≤ ≥
    0x221E,  # ∞
}


# Пресеты: ключ -> список категорий (ключ, метка, кодпойнты).
PRESETS: dict[str, list[tuple[str, str, set[int]]]] = {
    "basic": [
        ("latin", "Латиница", LATIN_BASIC),
        ("cyrillic", "Кириллица", CYRILLIC_RU),
        ("diacritics", "Диакритика", DIACRITICS_BASIC),
        ("punctuation", "Пунктуация и знаки", PUNCTUATION_BASIC),
    ],
    "extended": [
        ("latin", "Латиница", LATIN_BASIC),
        ("cyrillic", "Кириллица", CYRILLIC_RU | CYRILLIC_EXT),
        ("diacritics", "Диакритика", DIACRITICS_BASIC | DIACRITICS_EXT),
        ("punctuation", "Пунктуация и знаки", PUNCTUATION_BASIC | PUNCTUATION_EXT),
    ],
}

DEFAULT_PRESET = "basic"


def get_preset(name: str) -> list[tuple[str, str, set[int]]]:
    """Категории пресета по имени; неизвестное имя → пресет по умолчанию."""
    return PRESETS.get(name, PRESETS[DEFAULT_PRESET])
